#Дано двузначное число. Вывести число, полученное при перестановке цифр исходного числа
#Кароче если проще меняем числа в двухзначных числах местами
a = int(input('Введите двухзначное число'))

#Выделяю цифры

guli = a // 10 #десять
zxc = a % 10 #еденицы

coc = zxc * 10 + guli

print('вот ТАКОЕ У нас получилось число после перестановки чисел:', coc)