# Запрашиваем у пользователя год и сразу преобразуем введённую строку в целое число
year = int(input('Введите год:'))

# Проверяем: делится ли год на 400 без остатка?
# Если да — это високосный год (например, 2000, 1600), в нём 366 дней
if year % 400 == 0:
    days = 366

# Если на 400 не делится, проверяем: делится ли на 100 без остатка?
# Если да — это НЕ високосный год (например, 1900, 2100), в нём 365 дней
elif year % 100 == 0:
    days = 365

# Если на 100 не делится, проверяем: делится ли на 4 без остатка?
# Если да — это високосный год (например, 2024, 2028), в нём 366 дней
elif year % 4 == 0:
    days = 366

# Во всех остальных случаях год обычный (не високосный) — 365 дней
else:
    days = 365

# Выводим результат: в каком году сколько дней
print(f"В {year} году {days} дней")
